"""APIs for CrOS Portage."""

import re
import datetime

from recipe_engine import recipe_api
from recipe_engine.util import exponential_retry


class PortageApi(recipe_api.RecipeApi):
  """A module for CrOS Portage steps."""

  def commit_package_uprevs(self):
    """Uprevs portage packages for all boards.

    Must be run with cwd inside a chromiumos source root.
    """
    cmd = [
        'vpython',
        'chromite/bin/cros_mark_as_stable',
        'commit',
        '--all',
        '--buildroot',
        self.m.src_state.workspace_path,
        '--overlay-type',
        'both',
    ]
    return self.m.step('commit portage package uprevs', cmd)

  @exponential_retry(retries=3, delay=datetime.timedelta(minutes=2))
  def push_package_uprevs(self, dryrun=False):
    """Pushes the changes generated by |uprev_portage_packages| to remote.

    Must be run with cwd inside a chromiumos source root.

    Args:
      dryrun (bool): If set, do everything except the actual push.
    """
    # TODO(crbug.com/916197): Pull git operations out of this script
    cmd = [
        'vpython',
        'chromite/bin/cros_mark_as_stable',
        'push',
        '--overlay-type',
        'both',
    ]
    if dryrun:
      cmd.append('--dryrun')
    return self.m.step('push portage package uprevs', cmd)
