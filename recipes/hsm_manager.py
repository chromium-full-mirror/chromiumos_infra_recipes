def RunSteps(api: RecipeApi, properties: HSMManagerProperties):
  if not properties.bug:
    raise StepFailure("`bug` is a required property.")

  has_create = properties.HasField("create_keys_hsm_request")
  has_finalize = properties.HasField("finalize_keys_hsm_request")
  if has_create == has_finalize:
    raise StepFailure(
        "Properties must include either `create_keys_hsm_request` or "
        "`finalize_keys_hsm_request`.")

  with api.step.nest("set up dependencies"):
    api.git.clone(
        "https://chromium.googlesource.com/chromiumos/chromite/",
        target_path=api.src_state.workspace_path / "infra/chromite-HEAD",
        branch="main",
        single_branch=True,
    )

    api.git.clone(
        "https://chromium.googlesource.com/chromiumos/chromite/",
        target_path=api.src_state.workspace_path / "infra/chromite",
        branch="main",
        single_branch=True,
    )

    release_keys_path = api.src_state.workspace_path.joinpath(
        "src/platform/signing/keys")
    api.git.clone(
        "https://chrome-internal.googlesource.com/chromeos/platform/release-keys",
        target_path=release_keys_path,
        branch="main",
        single_branch=True,
    )

  if has_create:
    return create_hsm_keys(api, properties, release_keys_path)
  return finalize_hsm_keys(api, properties, release_keys_path)


def create_hsm_keys(api: RecipeApi, properties: HSMManagerProperties,
                    release_keys_path):
  with api.step.nest("create HSM keys"):
    docker_image = api.signing.signing_docker_image
    api.step(
        "docker auth",
        [
            "gcloud",
            "auth",
            "configure-docker",
            "us-docker.pkg.dev",
        ],
    )
    api.step(
        "docker pull",
        [
            "docker",
            "pull",
            docker_image,
        ],
    )
    api.easy.set_properties_step(signing_docker_image=docker_image)

    is_staging = api.build_menu.is_staging
    work_dir = api.path.mkdtemp(prefix="hsm_keygen_work_")
    create_keys_hsm_request, error_msg = api.keyset_utils.create_hsm_request(
        properties.create_keys_hsm_request,
        release_keys_path,
        docker_image,
        is_staging,
        build_target=properties.build_target,
        is_mp=properties.is_mp if properties.HasField("is_mp") else None,
        work_dir=work_dir,
    )
    if error_msg:
      return result_pb2.RawResult(
          status=common_pb2.FAILURE,
          summary_markdown=f"Keyset Validation Failed\n\n{error_msg}",
      )

    api.cros_build_api.SigningService.CreateKeysHsm(create_keys_hsm_request)

    inbox_uri = None
    if properties.quorum_artifacts_to_stage and properties.quorum_inbox_bucket:
      keyset_work_dir = work_dir / create_keys_hsm_request.keyset_name
      quorum_inbox = api.path.mkdtemp(prefix="quorum_inbox_")
      api.keyset_utils.stage_quorum_inbox(
          keyset_work_dir,
          quorum_inbox,
          list(properties.quorum_artifacts_to_stage),
      )

      build_id = api.buildbucket.build.id or 0
      dest_path = f"quorum_inbox/{create_keys_hsm_request.keyset_name}/{build_id}"
      api.gsutil.upload(
          source=quorum_inbox,
          bucket=properties.quorum_inbox_bucket,
          dest=dest_path,
          args=["-r"],
          name="upload to quorum inbox",
      )
      inbox_uri = f"gs://{properties.quorum_inbox_bucket}/{dest_path}"

    with api.step.nest("commit keyset to release-keys"), api.context(
        cwd=release_keys_path):
      commit_lines = [
          f"Create HSM keys for {create_keys_hsm_request.keyset_name}",
          "",
          f"Generated by hsm-manager, see {api.buildbucket.build_url()} for job details.",
      ]
      if is_staging:
        commit_lines += [
            "This CL was created for staging, it is not meant to be submitted."
        ]
      commit_lines += [
          "",
          f"BUG=b:{properties.bug}",
          "TEST=CQ",
      ]

      # Regenerate generated files.
      api.step(
          "regenerate generated files",
          ["./keyset/public/scripts/regenerate_keysets.sh", "--all"],
      )

      api.git.add_all()
      api.git.commit("\n".join(commit_lines) + "\n")

      reviewers = [] if is_staging else ["croskeymanagers@google.com"]
      invoker = api.cros_try.get_invoker()
      change = api.gerrit.create_change(
          str(release_keys_path),
          project_path=release_keys_path,
          non_repo_checkout=True,
          reviewers=reviewers,
          ccs=[invoker] if invoker else [],
      )
      api.easy.set_properties_step(
          keyset_commit=api.gerrit.parse_gerrit_change_url(change))
      if inbox_uri:
        api.easy.set_properties_step(quorum_inbox_uri=inbox_uri)

      if is_staging:
        api.gerrit.abandon_change(change)

    if inbox_uri:
      api.keyset_utils.prepare_quorum_notification(
          keyset_name=create_keys_hsm_request.keyset_name,
          inbox_uri=inbox_uri,
          is_staging=is_staging,
      )

    summary_markdown = f"Keyset created: {create_keys_hsm_request.keyset_name}"
    if inbox_uri:
      summary_markdown += f"\n\nStaged quorum inbox: `{inbox_uri}`"
    return result_pb2.RawResult(
        status=common_pb2.SUCCESS,
        summary_markdown=summary_markdown,
    )


def finalize_hsm_keys(api: RecipeApi, properties: HSMManagerProperties,
                      release_keys_path):
  with api.step.nest("finalize HSM keys"):
    if not properties.quorum_build_id:
      raise StepFailure("`quorum_build_id` is a required property.")

    is_staging = api.build_menu.is_staging
    quorum_build = api.buildbucket.get(
        properties.quorum_build_id,
        step_name="get quorum build",
    )
    docker_image = api.keyset_utils.get_docker_image(quorum_build)
    api.keyset_utils.validate_quorum_build(
        quorum_build,
        is_staging=is_staging,
        quorum_inbox_bucket=properties.quorum_inbox_bucket,
    )

    api.step(
        "docker auth",
        [
            "gcloud",
            "auth",
            "configure-docker",
            "us-docker.pkg.dev",
        ],
    )
    api.step(
        "docker pull",
        [
            "docker",
            "pull",
            docker_image,
        ],
    )

    work_dir = api.path.mkdtemp(prefix="hsm_finalize_work_")
    finalize_request = api.keyset_utils.finalize_hsm_request(
        properties.finalize_keys_hsm_request,
        release_keys_path,
        docker_image,
        is_staging,
        work_dir=work_dir,
    )

    inbox_bucket, inbox_path = api.keyset_utils.get_quorum_inbox(
        quorum_build,
        finalize_request.keyset_name,
    )
    outbox_bucket, outbox_path = api.keyset_utils.get_quorum_outbox(
        quorum_build,
        finalize_request.keyset_name,
    )
    inbox_artifacts, outbox_artifacts = (
        api.keyset_utils.download_quorum_artifacts(
            work_dir=work_dir,
            quorum_build=quorum_build,
            keyset_name=finalize_request.keyset_name,
        ))

    api.cros_build_api.SigningService.FinalizeKeysHsm(finalize_request)

    summary_lines = [
        f"Keyset finalized: {finalize_request.keyset_name}",
        "",
        f"- Quorum inbox (`gs://{inbox_bucket}/{inbox_path}/`): "
        f"{len(inbox_artifacts)} artifact(s)",
        f"- Quorum outbox (`gs://{outbox_bucket}/{outbox_path}/`): "
        f"{len(outbox_artifacts)} artifact(s)",
    ]
    return result_pb2.RawResult(
        status=common_pb2.SUCCESS,
        summary_markdown="\n".join(summary_lines),
    )


