def GenTests(api: RecipeTestApi):
  yield api.test(
      "hsm-create-keys",
      api.properties(
          HSMManagerProperties(
              create_keys_hsm_request=CreateKeysHsmRequest(
                  keyset_name="FooPreMPKeys"), bug=12345)),
      api.post_check(
          post_process.MustRun,
          "create HSM keys.call chromite.api.SigningService/CreateKeysHsm"),
      # TODO(b/505067810): Commit keyset to release-keys after files changes.
      # api.post_check(
      #     post_process.MustRun,
      #     "create HSM keys.commit keyset to release-keys.regenerate generated files"
      # ),
      api.post_process(post_process.DropExpectation),
  )

  yield api.test(
      "staging-hsm-create-keys",
      api.buildbucket.build(
          build_pb2.Build(
              builder=builder_common_pb2.BuilderID(
                  project="chromeos",
                  bucket="staging",
                  builder="staging-hsm-manager",
              ))),
      api.properties(
          HSMManagerProperties(
              create_keys_hsm_request=CreateKeysHsmRequest(
                  keyset_name="FooPreMPKeys"), bug=12345)),
      api.post_check(
          post_process.MustRun,
          "create HSM keys.call chromite.api.SigningService/CreateKeysHsm"),
      # TODO(b/505067810): Commit keyset to release-keys after files changes.
      # api.post_check(
      #     post_process.MustRun,
      #     "create HSM keys.commit keyset to release-keys.abandon CL 1"),
      api.post_process(post_process.DropExpectation),
  )

  yield api.test(
      "missing-bug",
      api.properties(
          HSMManagerProperties(
              create_keys_hsm_request=CreateKeysHsmRequest(
                  keyset_name="FooPreMPKeys")),
      ),
      api.post_check(post_process.SummaryMarkdown,
                     "`bug` is a required property."),
      api.post_process(post_process.DropExpectation),
      status="FAILURE",
  )

  yield api.test(
      "missing-request",
      api.properties(
          HSMManagerProperties(bug=123),
      ),
      api.post_check(post_process.SummaryMarkdown,
                     "`create_keys_hsm_request` is a required property."),
      api.post_process(post_process.DropExpectation),
      status="FAILURE",
  )
