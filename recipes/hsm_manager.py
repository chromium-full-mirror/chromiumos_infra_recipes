def RunSteps(api: RecipeApi, properties: HSMManagerProperties):
  if not properties.bug:
    raise StepFailure("`bug` is a required property.")

  if not properties.HasField("create_keys_hsm_request"):
    raise StepFailure("`create_keys_hsm_request` is a required property.")

  with api.step.nest("set up dependencies"):
    api.git.clone(
        "https://chromium.googlesource.com/chromiumos/chromite/",
        target_path=api.src_state.workspace_path / "infra/chromite-HEAD",
        branch="main",
        single_branch=True,
    )

    api.git.clone(
        "https://chromium.googlesource.com/chromiumos/chromite/",
        target_path=api.src_state.workspace_path / "infra/chromite",
        branch="main",
        single_branch=True,
    )

    release_keys_path = api.src_state.workspace_path.joinpath(
        "src/platform/signing/keys")
    api.git.clone(
        "https://chrome-internal.googlesource.com/chromeos/platform/release-keys",
        target_path=release_keys_path,
        branch="main",
        single_branch=True,
    )

  with api.step.nest("create HSM keys"):
    api.step(
        "docker auth",
        [
            "gcloud",
            "auth",
            "configure-docker",
            "us-docker.pkg.dev",
        ],
    )
    api.step(
        "docker pull",
        [
            "docker",
            "pull",
            api.signing.signing_docker_image,
        ],
    )

    is_staging = api.build_menu.is_staging
    create_keys_hsm_request = properties.create_keys_hsm_request
    # These fields shouldn't be set by the user, but in any case
    # set them here (potentially overwriting existing values).
    create_keys_hsm_request.docker_image = api.signing.signing_docker_image
    create_keys_hsm_request.release_keys_checkout = str(release_keys_path)
    # Default to dry run in staging.
    if not create_keys_hsm_request.HasField("dry_run"):
      create_keys_hsm_request.dry_run = is_staging
    api.cros_build_api.SigningService.CreateKeysHsm(create_keys_hsm_request)

    # TODO(b/505067933): Notify quorum members that there is a new quorum operation.

